    private void dropboxFile(String id, long size, long seed) {
        provider.files.put(id, new Generated.File(size, seed, REV));
        meta.files.put(box + "/" + id, new MetadataSource.FileMeta(id, "DROPBOX", "FILE", size, REV, true));
    }

    private void googleFile(String id, long size, long seed) {
        provider.files.put(id, new Generated.File(size, seed, null));
        meta.files.put(drive + "/" + id, new MetadataSource.FileMeta(id, "GOOGLE_DRIVE", "FILE", size, "0Bhead", true));
    }

    /** Plays Electron main: answers every renewal request with a fresh delegated credential. */
    private Future<Integer> renewer(int expectedRequests) {
        return pool.submit(() -> {
            int answered = 0;
            long until = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            while (answered < expectedRequests && System.nanoTime() < until) {
                for (UUID account : broker.poll(mount.generation(), Duration.ofSeconds(1))) {
                    boolean dropbox = account.equals(box);
                    broker.install(mount.generation(), dropbox ? Provider.DROPBOX : Provider.GOOGLE_DRIVE, account, TOKEN,
                            clock.instant().plusSeconds(3600), dropbox ? "777" : null);
                    answered++;
                }
            }
            return answered;
        });
    }

    private void installDirect(UUID account) throws Exception {
        broker.poll(mount.generation(), Duration.ZERO); // nothing pending yet
        credentials.install(account.equals(box) ? Provider.DROPBOX : Provider.GOOGLE_DRIVE, account, TOKEN,
                clock.instant().plusSeconds(3600), account.equals(box) ? "777" : null);
    }

    private ReadService.ReadResult read(String handle, long offset, long length) throws ReadException {
        return service.read(mount, handle, offset, length);
    }

    @Test
    void openReadCloseWithOneDeduplicatedRenewalForConcurrentReaders() throws Exception {
        dropboxFile("id:f1", 10 * 1024 * 1024 + 3, 7);
        VfsReadService.Opened opened = service.open(mount, box, "id:f1", 10 * 1024 * 1024 + 3);
        assertThat(opened.handle()).matches("^hdf_[A-Za-z0-9_-]{43}$");
        assertThat(opened.consistency()).isEqualTo("dropbox-revision-pinned");
        assertThat(opened.revisionPinned()).isTrue();
        assertThat(opened.toString()).doesNotContain(opened.handle());

        // Four readers start before any credential exists: exactly one renewal request.
        List<Future<ReadService.ReadResult>> readers = new ArrayList<>();
        for (int i = 0; i < 4; i++) {
            long offset = i * 1_000_000L;
            readers.add(pool.submit(() -> read(opened.handle(), offset, 100_000)));
        }
        Future<Integer> renewals = renewer(1);
        for (int i = 0; i < 4; i++) {
            ReadService.ReadResult r = readers.get(i).get(10, TimeUnit.SECONDS);
            assertThat(r.data()).hasSize(100_000).isEqualTo(expected(7, i * 1_000_000L, 100_000));
        }
        assertThat(renewals.get(10, TimeUnit.SECONDS)).isEqualTo(1);
        assertThat(service.stats().get("renewals").toString()).contains("requested=1", "installed=1");

        assertThat(service.close(mount, opened.handle())).isTrue();
        assertThat(service.close(mount, opened.handle())).isFalse();
        assertThatThrownBy(() -> read(opened.handle(), 0, 10)).isInstanceOf(ReadException.class)
                .extracting(e -> ((ReadException) e).code()).isEqualTo("stale_handle");
    }

    @Test
    void sequentialRandomCrossChunkAndEofReadsAreExact() throws Exception {
        long size = 3L * MIB4 + 12_345;
        dropboxFile("id:f2", size, 11);
        installDirect(box);
        String h = service.open(mount, box, "id:f2", size).handle();
        long offset = 0;
        while (offset < size) { // sequential, 4 MiB at a time
            ReadService.ReadResult r = read(h, offset, MIB4);
            int want = (int) Math.min(MIB4, size - offset);
            assertThat(r.length()).isEqualTo(want);
            assertThat(r.data()).isEqualTo(expected(11, offset, want));
            assertThat(r.eof()).isEqualTo(offset + want == size);
            offset += want;
        }
        ReadService.ReadResult cross = read(h, MIB4 - 10, 20); // crosses the 4 MiB chunk boundary
        assertThat(cross.data()).isEqualTo(expected(11, MIB4 - 10, 20));
        java.util.Random random = new java.util.Random(5);
        for (int i = 0; i < 20; i++) {
            long at = (long) (random.nextDouble() * size);
            int len = 1 + random.nextInt(300_000);
            ReadService.ReadResult r = read(h, at, len);
            int want = (int) Math.min(len, size - at);
            assertThat(r.data()).as("offset " + at).isEqualTo(expected(11, at, want));
        }
        ReadService.ReadResult tail = read(h, size - 5, 100);
        assertThat(tail.length()).isEqualTo(5);
        assertThat(tail.eof()).isTrue();
        ReadService.ReadResult atEof = read(h, size, 100);
        assertThat(atEof.length()).isZero();
        assertThat(atEof.eof()).isTrue();
        assertThat(read(h, size + 1_000_000, 1).length()).isZero();
        assertThatThrownBy(() -> read(h, 0, MIB4 + 1)).extracting(e -> ((ReadException) e).code()).isEqualTo("invalid_request");
        assertThatThrownBy(() -> read(h, Long.MAX_VALUE - 1, 10)).extracting(e -> ((ReadException) e).code())
                .isEqualTo("invalid_request");
        assertThatThrownBy(() -> read(h, -1, 10)).extracting(e -> ((ReadException) e).code()).isEqualTo("invalid_request");
    }

    @Test
    void filesLargerThan4GiBUse64BitOffsetsThroughTheEncryptedCache() throws Exception {
        long size = 5 * GIB + 777;
        dropboxFile("id:big", size, 99);
        installDirect(box);
        String h = service.open(mount, box, "id:big", size).handle();
        long at = 4 * GIB + MIB4 - 100; // beyond 2^32, crossing a chunk boundary
        ReadService.ReadResult first = read(h, at, 1000);
        assertThat(first.data()).isEqualTo(expected(99, at, 1000));
        assertThat(first.cacheBytes()).isZero();
        assertThat(first.providerBytes()).isGreaterThan(1000); // whole chunks on an eligible miss
        ReadService.ReadResult again = read(h, at, 1000);
        assertThat(again.data()).isEqualTo(first.data());
        assertThat(again.cacheBytes()).isEqualTo(1000);
        assertThat(again.providerBytes()).isZero();
        ReadService.ReadResult end = read(h, size - 7, MIB4);
        assertThat(end.length()).isEqualTo(7);
        assertThat(end.data()).isEqualTo(expected(99, size - 7, 7));
        assertThat(end.eof()).isTrue();
        assertThat(provider.revisionsAsked).containsOnly(REV);
    }

    @Test
    void googleReadsBypassTheCacheAndDetectASizeChange() throws Exception {
        googleFile("gfile1", 6 * 1024 * 1024 + 5, 3);
        installDirect(drive);
        VfsReadService.Opened opened = service.open(mount, drive, "gfile1", 6 * 1024 * 1024 + 5);
        assertThat(opened.consistency()).isEqualTo("google-unpinned");
        assertThat(opened.revisionPinned()).isFalse();
        for (int i = 0; i < 2; i++) {
            ReadService.ReadResult r = read(opened.handle(), 100, 5000);
            assertThat(r.data()).isEqualTo(expected(3, 100, 5000));
            assertThat(r.cache()).isEqualTo(ChunkCache.Outcome.BYPASS);
            assertThat(r.bypassReason()).isEqualTo("provider_not_version_bound");
            assertThat(r.providerBytes()).isEqualTo(5000);
            assertThat(r.cacheBytes()).isZero();
        }
        // The file grew remotely: the next range reports another total size and fails, never mixes.
        provider.files.put("gfile1", new Generated.File(7 * 1024 * 1024, 4, null));
        assertThatThrownBy(() -> read(opened.handle(), 100, 5000)).extracting(e -> ((ReadException) e).code())
                .isEqualTo("file_changed");
    }

    @Test
    void aDropboxHandleStaysOnItsRevisionAndFailsWhenItDisappears() throws Exception {
        long size = 9L * 1024 * 1024;
        dropboxFile("id:rv", size, 21);
        installDirect(box);
        String h = service.open(mount, box, "id:rv", size).handle();
        assertThat(read(h, 0, 10).data()).isEqualTo(expected(21, 0, 10));
        // A newer revision with the same size replaces the old one at the provider.
        provider.files.put("id:rv", new Generated.File(size, 22, "fedcba98765"));
        // Chunk 0 of the pinned revision is still served from the encrypted cache (it IS that revision)...
        assertThat(read(h, 5, 5).data()).isEqualTo(expected(21, 5, 5));
        // ...but an uncached range asks for rev:<pinned> only, and fails instead of switching.
        assertThatThrownBy(() -> read(h, 2L * MIB4 + 1, 10)).extracting(e -> ((ReadException) e).code()).isEqualTo("not_found");
        assertThat(provider.revisionsAsked).containsOnly(REV);
        // A new open sees (and pins) the new revision.
        meta.files.put(box + "/id:rv", new MetadataSource.FileMeta("id:rv", "DROPBOX", "FILE", size, "fedcba98765", true));
        String h2 = service.open(mount, box, "id:rv", size).handle();
        assertThat(read(h2, 2L * MIB4 + 1, 10).data()).isEqualTo(expected(22, 2L * MIB4 + 1, 10));
        assertThat(read(h2, 5, 5).data()).isEqualTo(expected(22, 5, 5)); // other revision, other cache entry
    }

