    @Test
    void replacingACredentialDoesNotCancelReadsUsingThePreviousOne() throws Exception {
        googleFile("gx", 1000, 1);
        installDirect(drive);
        String h = service.open(mount, drive, "gx", 1000).handle();
        provider.gate = new CountDownLatch(1);
        Future<String> reader = pool.submit(() -> code(() -> read(h, 0, 100)));
        assertThat(provider.entered.await(5, TimeUnit.SECONDS)).isTrue();
        // e.g. a Verify read in the app delegates a new credential for the same account meanwhile.
        credentials.install(Provider.GOOGLE_DRIVE, drive, TOKEN + "-new", clock.instant().plusSeconds(3600), null);
        provider.gate.countDown();
        assertThat(reader.get(5, TimeUnit.SECONDS)).isEqualTo("ok");
        // ...but clearing the account (disconnect) still cancels.
        provider.gate = new CountDownLatch(1);
        CountDownLatch entered = new CountDownLatch(1);
        AtomicReference<String> result = new AtomicReference<>();
        Future<?> second = pool.submit(() -> {
            entered.countDown();
            result.set(code(() -> read(h, 0, 100)));
        });
        entered.await();
        Thread.sleep(100);
        credentials.clear(drive);
        second.get(5, TimeUnit.SECONDS);
        assertThat(result.get()).isEqualTo("cancelled");
    }

