    /** A clock tests can move forward. */
    static final class MutableClock extends Clock {
        volatile Instant now = Instant.parse("2026-11-27T10:00:00Z");

        @Override
        public ZoneOffset getZone() {
            return ZoneOffset.UTC;
        }

        @Override
        public Clock withZone(java.time.ZoneId zone) {
            return this;
        }

        @Override
        public Instant instant() {
            return now;
        }

        void advance(Duration d) {
            now = now.plus(d);
        }
    }

    /** Deterministic generated bytes: no file is ever held in memory. */
    static byte gen(long seed, long p) {
        long lo = p & 0xffffffffL;
        long hi = p >>> 32;
        return (byte) ((lo * 7 + hi * 13 + (lo >>> 11) + seed) & 0xff);
    }

    static byte[] expected(long seed, long offset, int length) {
        byte[] b = new byte[length];
        for (int i = 0; i < length; i++) {
            b[i] = gen(seed, offset + i);
        }
        return b;
    }

    /** Fake provider: generated content per file id, a current revision, failure switches. */
    static final class Generated implements RangeReader {
        record File(long size, long seed, String rev) {
        }

        final Map<String, File> files = new ConcurrentHashMap<>();
        final List<String> revisionsAsked = new CopyOnWriteArrayList<>();
        final AtomicInteger calls = new AtomicInteger();
        final AtomicInteger rejectNext = new AtomicInteger();
        volatile CountDownLatch gate;
        final CountDownLatch entered = new CountDownLatch(1);

        @Override
        public ProviderReader.Result read(Credential credential, String fileId, long start, long end, long expectedSize,
                String expectedRevision, CancelToken cancel) throws ReadException {
            calls.incrementAndGet();
            entered.countDown();
            revisionsAsked.add(String.valueOf(expectedRevision));
            CountDownLatch g = gate;
            if (g != null) {
                try {
                    while (!g.await(5, TimeUnit.MILLISECONDS)) {
                        if (cancel.isCancelled()) {
                            throw new ReadException("cancelled", 409);
                        }
                    }
                } catch (InterruptedException e) {
                    throw new ReadException("cancelled", 409);
                }
            }
            if (rejectNext.getAndUpdate(n -> Math.max(0, n - 1)) > 0) {
                throw new ReadException("credential_rejected", 409);
            }
            File f = files.get(fileId);
            if (f == null) {
                throw new ReadException("not_found", 404);
            }
            boolean dropbox = credential.provider() == Provider.DROPBOX;
            if (dropbox && expectedRevision != null && !expectedRevision.equals(f.rev())) {
                throw new ReadException("not_found", 404); // rev:<old> no longer exists: never the new content
            }
            if (f.size() != expectedSize) {
                throw new ReadException("file_changed", 409); // Content-Range total differs
            }
            int n = Math.toIntExact(end - start + 1);
            return new ProviderReader.Result(expected(f.seed(), start, n), n, dropbox && expectedRevision != null,
                    dropbox ? f.rev() : null);
        }
    }

    /** Fake backend metadata, by account and file id. */
    static final class Meta implements MetadataSource {
        final Map<String, FileMeta> files = new ConcurrentHashMap<>();
        final AtomicInteger calls = new AtomicInteger();

        @Override
        public List<Account> accounts(MountRegistry.Mount mount) {
            return List.of();
        }

        @Override
        public Page files(MountRegistry.Mount mount, UUID accountId, String directory, String continuation, int pageSize) {
            return new Page(List.of(), null);
        }

        @Override
        public FileMeta file(MountRegistry.Mount mount, UUID accountId, String fileId) throws MetadataException {
            calls.incrementAndGet();
            FileMeta m = files.get(accountId + "/" + fileId);
            if (m == null) {
                throw new MetadataException("not_found", 404);
            }
            return m;
        }
    }

