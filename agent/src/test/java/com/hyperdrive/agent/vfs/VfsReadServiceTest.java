    @Test
    void aRenewalFailureFailsWaitersAtOnceAndPermanentOnesDoNotRetry() throws Exception {
        dropboxFile("id:r", 10, 1);
        String h = service.open(mount, box, "id:r", 10).handle();
        Future<String> waiting = pool.submit(() -> code(() -> read(h, 0, 10)));
        List<UUID> requested = broker.poll(mount.generation(), Duration.ofSeconds(5));
        assertThat(requested).containsExactly(box);
        broker.fail(mount.generation(), box, "needs_reconnect");
        assertThat(waiting.get(5, TimeUnit.SECONDS)).isEqualTo("needs_reconnect");
        // No storm: the next reads fail immediately without asking again.
        long t0 = System.nanoTime();
        assertThat(code(() -> read(h, 0, 10))).isEqualTo("needs_reconnect");
        assertThat(TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - t0)).isLessThan(500);
        assertThat(broker.poll(mount.generation(), Duration.ZERO)).isEmpty();
        assertThat(broker.requested.get()).isEqualTo(1);
        // Transient failures back off, then a new request is allowed.
        assertThatThrownBy(() -> broker.fail(mount.generation(), box, "unknown_code")).isInstanceOf(ReadException.class);
        newMount();
        String h2 = service.open(mount, box, "id:r", 10).handle();
        Future<String> again = pool.submit(() -> code(() -> read(h2, 0, 10)));
        assertThat(broker.poll(mount.generation(), Duration.ofSeconds(5))).containsExactly(box);
        broker.fail(mount.generation(), box, "backend_unavailable");
        assertThat(again.get(5, TimeUnit.SECONDS)).isEqualTo("backend_unavailable");
        assertThat(code(() -> read(h2, 0, 10))).isEqualTo("backend_unavailable");
        clock.advance(CredentialBroker.TRANSIENT_BACKOFF.plusSeconds(1));
        Future<Integer> renewals = renewer(1);
        assertThat(code(() -> read(h2, 0, 10))).isEqualTo("ok");
        assertThat(renewals.get(10, TimeUnit.SECONDS)).isEqualTo(1);
    }

